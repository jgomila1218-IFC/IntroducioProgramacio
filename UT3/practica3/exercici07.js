// "==" compara que els valors siguin iguals independentent de la seva clase
//"===" compara que els valors siguin iguals també en la seva clase.
console.log(5 == "5"); //els valors son iguals --> True
console.log(5 === "5"); //els valors son iguals pero la clase es diferent --> False
console.log(0 == false); //els valors son iguals --> True
console.log(0 === false); //els valors son iguals pero la clase es diferent --> False